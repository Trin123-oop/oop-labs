package lab1;

public class Book {
        private String title;
        private String author;
        private double price;
        
        public Book (String title, String name, double price){
            this.title = title;
            author = name;
            this.price = price;
        }
        public void setTitle(String title){
            this.title = title;
        }
        public void setAuthor(String author){
            this.author = author;
        }

    }

